/* URL ridimensionato dal CDN di Unsplash */
window.FD_MEDIA.url = function (m, w, h, extra) {
  if (!m) return "";
  const q = new URLSearchParams({ w: String(w), q: "72", auto: "format" });
  if (h) { q.set("h", String(h)); q.set("fit", "crop"); q.set("crop", (extra && extra.crop) || "faces,entropy"); }
  return m.src + "?" + q.toString();
};
